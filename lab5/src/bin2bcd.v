module bin2bcd (
    input  wire [31:0] bin,
    output reg  [31:0] bcd 
);

    // Для 32-битного входа: максимум 10 BCD цифр → 40 бит
    // Делаем temp = 40 (BCD) + 32 (bin) = 72 бита
    reg [71:0] temp;
    integer i;

    always @* begin
        // Загружаем bin в младшие 32 бита, старшие 40 — нули (для BCD)
        temp = {40'd0, bin};

        // 32 итерации — по числу битов входа
        for (i = 0; i < 32; i = i + 1) begin
            // Коррекция +3 для каждой 4-битной группы в BCD-части (10 групп)
            if (temp[71:68] > 4) temp[71:68] = temp[71:68] + 3;
            if (temp[67:64] > 4) temp[67:64] = temp[67:64] + 3;
            if (temp[63:60] > 4) temp[63:60] = temp[63:60] + 3;
            if (temp[59:56] > 4) temp[59:56] = temp[59:56] + 3;
            if (temp[55:52] > 4) temp[55:52] = temp[55:52] + 3;
            if (temp[51:48] > 4) temp[51:48] = temp[51:48] + 3;
            if (temp[47:44] > 4) temp[47:44] = temp[47:44] + 3;
            if (temp[43:40] > 4) temp[43:40] = temp[43:40] + 3;
            if (temp[39:36] > 4) temp[39:36] = temp[39:36] + 3;
            if (temp[35:32] > 4) temp[35:32] = temp[35:32] + 3;

            // Сдвиг влево на 1 бит
            temp = temp << 1;
        end

        // После 32 сдвигов: BCD-цифры находятся в старших 40 битах: temp[71:32]
        // Это 10 цифр: [D9 D8 D7 D6 D5 D4 D3 D2 D1 D0]
        // Нам нужны **младшие 8 цифр** → D7..D0 → это биты [63:32] (8×4=32 бита)
        bcd = temp[63:32];
    end

endmodule